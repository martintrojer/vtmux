//! Display width of a character as the reference tmux 3.8 computes it.
//!
//! This is `utf8_width` (utf8.c:561-590) in a build without utf8proc, the
//! reference here: tmux's built-in override table first, then glibc's
//! `wcwidth(3)` in an `en_US.UTF-8` locale, then tmux's fix-ups (a negative
//! width is 0 for the C1 controls U+0080-U+009F and 1 otherwise). The glibc
//! part is a table of the code points it gives width 0 or 2 (everything else
//! outside ASCII is 1), dumped from the reference host's glibc 2.43 by calling
//! `wcwidth` on every code point; `tests/style_cases.sh` pins a spread of them
//! against `#{w:}` on the reference.
//!
//! The four tables are regenerated by `tests/style_cases.sh` (glibc's from a
//! C program calling `wcwidth` on every code point, tmux's from `utf8.c` and
//! `utf8-combined.c`), which also checks them against `#{w:}` on the reference.
//!
//! The core stays pure: no libghostty and no `libc`. On a build linked with
//! utf8proc tmux would give other widths for some code points; that is the
//! reference's own configuration difference, not ours to guess.
//!
//! [`char_width`] is one code point. [`text_width`] is `format_width`'s walk
//! (format-draw.c:1128-1160) without the `#[...]` handling: tmux first
//! reads a whole UTF-8 character, and only that character's width counts, so
//! it does not merge combining sequences itself (the *screen* merges them,
//! see [`Cluster`]). [`Cluster`] is what `screen_write_combine`
//! (screen-write.c:2850) builds as it writes cells one at a time.

