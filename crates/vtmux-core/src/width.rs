fn in_ranges(table: &[(u32, u32)], c: u32) -> bool {
    table
        .binary_search_by(|&(lo, hi)| {
            if c < lo {
                std::cmp::Ordering::Greater
            } else if c > hi {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// The width tmux gives `c`: 0, 1 or 2.
#[must_use]
pub fn char_width(c: char) -> u8 {
    let cp = u32::from(c);
    if let Ok(i) = OVERRIDES.binary_search_by_key(&cp, |&(wc, _)| wc) {
        return OVERRIDES[i].1;
    }
    if cp < 0x80 {
        // `wcwidth` is -1 for the control characters, which tmux maps to 1; the
        // callers that care (format_width) skip them before asking.
        return 1;
    }
    if in_ranges(ZERO, cp) {
        0
    } else if in_ranges(WIDE, cp) {
        2
    } else {
        1
    }
}

/// `format_width` (format-draw.c:1128) for text without `#[...]` styles:
/// printable ASCII is 1, control characters and anything not valid UTF-8 are
/// skipped, every other character counts its own [`char_width`] (so a
/// combining mark adds 0, but an emoji modifier adds its own 2 here, where the
/// screen would merge it).
#[must_use]
pub fn text_width(s: &str) -> usize {
    s.chars()
        .map(|c| match c {
            '\u{20}'..='\u{7e}' => 1,
            c if u32::from(c) < 0x80 => 0,
            c => usize::from(char_width(c)),
        })
        .sum()
}

fn is_zwj(c: char) -> bool {
    c == '\u{200d}'
}

fn is_vs16(c: char) -> bool {
    c == '\u{fe0f}'
}

fn is_regional(c: char) -> bool {
    ('\u{1f1e6}'..='\u{1f1ff}').contains(&c)
}

fn is_skin_tone(c: char) -> bool {
    ('\u{1f3fb}'..='\u{1f3ff}').contains(&c)
}

#[derive(PartialEq, Eq)]
enum Jamo {
    No,
    Choseong,
    Jungseong,
    Jongseong,
}

/// `hanguljamo_get_class` (utf8-combined.c:262-290) over code points.
fn jamo(c: char) -> Jamo {
    match u32::from(c) {
        0x1100..=0x115f | 0xa960..=0xa97c => Jamo::Choseong,
        0x1160..=0x11a7 | 0xd7b0..=0xd7c6 => Jamo::Jungseong,
        0x11a8..=0x11ff | 0xd7cb..=0xd7fb => Jamo::Jongseong,
        _ => Jamo::No,
    }
}

/// What `screen_write_combine` decides for a character written after a cell.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Combine {
    /// It was folded into the previous cell.
    Joined,
    /// It starts a cell of its own.
    Own,
    /// It is thrown away (a zero-width character with nothing to join, a
    /// Hangul jamo that cannot compose, U+3164).
    Dropped,
}

/// A cell's worth of text as the status line's screen builds it: a base
/// character plus what `screen_write_combine` (screen-write.c:2850-2985) folds
/// in. tmux keeps a cell's text in 32 bytes, so a longer sequence stops
/// combining there.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Cluster {
    pub text: String,
    /// Columns the cell covers: 1 or 2.
    pub width: u8,
}

/// `UTF8_SIZE`.
const CELL_BYTES: usize = 32;

/// `screen_write_combine` for a character written with no cell before it
/// (cursor at column 0): zero-width characters vanish.
#[must_use]
pub fn combine_at_start(c: char) -> Combine {
    if c == '\u{3164}' || is_zwj(c) || is_vs16(c) || char_width(c) == 0 {
        Combine::Dropped
    } else {
        Combine::Own
    }
}

impl Cluster {
    /// Start a cell from a character that has a width (not dropped).
    #[must_use]
    pub fn new(c: char) -> Self {
        Self {
            text: c.to_string(),
            width: char_width(c),
        }
    }

    /// `screen_write_combine` (screen-write.c:2850): write `c` after this
    /// cell. On [`Combine::Joined`] the cell has absorbed it (and may have
    /// become 2 wide: the caller then owes a padding column).
    pub fn push(&mut self, c: char) -> Combine {
        if c == '\u{3164}' {
            return Combine::Dropped;
        }
        let zero_width = is_zwj(c) || is_vs16(c) || char_width(c) == 0;
        let none = if zero_width {
            Combine::Dropped
        } else {
            Combine::Own
        };
        // ASCII never combines.
        if c.len_utf8() < 2 {
            return none;
        }
        let mut force_wide = is_vs16(c);
        let first = self.text.chars().next().unwrap_or(' ');
        let last = self.text.chars().next_back().unwrap_or(' ');
        if !zero_width {
            match (jamo(c), jamo(last), last.len_utf8()) {
                (Jamo::Choseong, _, _) => return Combine::Own,
                (Jamo::Jungseong, Jamo::Choseong, 3) | (Jamo::Jongseong, Jamo::Jungseong, 3) => {}
                (Jamo::Jungseong | Jamo::Jongseong, _, _) => return Combine::Dropped,
                (Jamo::No, ..) => {
                    // utf8_should_combine, tried both ways round
                    // (utf8-combined.c:105-205): the tests look at the first
                    // character of each side.
                    let flags = is_regional(c)
                        && is_regional(first)
                        && self.text.chars().filter(|&x| is_regional(x)).count() == 1;
                    let skin = (is_skin_tone(c) && SKIN_BASES.contains(&u32::from(first)))
                        || (is_skin_tone(first) && SKIN_BASES.contains(&u32::from(c)));
                    if flags || skin {
                        force_wide = true;
                    } else if !self.text.ends_with('\u{200d}') {
                        return Combine::Own;
                    }
                }
            }
        }
        if self.text.len() + c.len_utf8() > CELL_BYTES {
            return none;
        }
        self.text.push(c);
        if self.width == 1 && force_wide {
            self.width = 2;
        }
        Combine::Joined
    }
}

