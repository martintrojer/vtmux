    #[test]
    fn tables_are_sorted_and_disjoint() {
        for table in [ZERO, WIDE] {
            for pair in table.windows(2) {
                assert!(pair[0].1 < pair[1].0, "{pair:x?}");
            }
        }
        assert!(OVERRIDES.windows(2).all(|p| p[0].0 < p[1].0));
        assert!(
            SKIN_BASES
                .iter()
                .all(|&c| OVERRIDES.binary_search_by_key(&c, |&(w, _)| w).is_ok()
                    || char::from_u32(c).is_some())
        );
    }

    #[test]
    fn skin_tone_widens_to_two() {
        let mut cell = Cluster::new('\u{1f44d}');
        assert_eq!(cell.push('\u{1f3fd}'), Combine::Joined);
        assert_eq!((cell.text.as_str(), cell.width), ("\u{1f44d}\u{1f3fd}", 2));
    }

    #[test]
    fn zero_width_joiner_builds_one_cell() {
        let mut cell = Cluster::new('\u{1f468}');
        assert_eq!(cell.push('\u{200d}'), Combine::Joined);
        assert_eq!(cell.push('\u{1f469}'), Combine::Joined);
        assert_eq!(cell.width, 2);
    }

    #[test]
    fn flags_combine_only_as_a_pair() {
        let mut cell = Cluster::new('\u{1f1ef}');
        assert_eq!(cell.push('\u{1f1f5}'), Combine::Joined);
        assert_eq!(cell.push('\u{1f1fa}'), Combine::Own);
    }

    #[test]
    fn ascii_never_combines_and_zero_width_without_a_base_drops() {
        let mut cell = Cluster::new('a');
        assert_eq!(cell.push('b'), Combine::Own);
        // A zero-width character joins whatever cell is before it (the new
        // character's size is all `screen_write_combine` looks at first).
        assert_eq!(cell.push('\u{301}'), Combine::Joined);
        assert_eq!(cell.text, "a\u{301}");
        assert_eq!(combine_at_start('\u{301}'), Combine::Dropped);
        assert_eq!(combine_at_start('a'), Combine::Own);
    }
