#!/usr/bin/env python3
"""Regenerates ctype_tables.rs from the host glibc: the iswctype(3), towupper(3) and
towlower(3) the reference tmux 3.8 matches with (regcomp/fnmatch in an en_US.UTF-8 or
C.UTF-8 locale; tmux.c:403).

    python3 crates/vtmux-core/src/regex/gen_ctype.py > crates/vtmux-core/src/regex/ctype_tables.rs

Only code points from U+0080 up are listed; ASCII is computed by the caller (C locale
rules). glibc's `graph` is alpha | punct and its `print` is `graph` plus the blank set
there, both checked below, so only alpha, upper, lower, punct, space, blank and cntrl are
stored. `digit` and `xdigit` have no non-ASCII members and `alnum` equals `alpha`."""
import ctypes

libc = ctypes.CDLL("libc.so.6")
libc.setlocale.restype = ctypes.c_char_p
if not (libc.setlocale(0, b"en_US.UTF-8") or libc.setlocale(0, b"C.UTF-8")):
    raise SystemExit("no UTF-8 locale")
libc.iswctype.argtypes = [ctypes.c_uint, ctypes.c_ulong]
libc.wctype.restype = ctypes.c_ulong
libc.towupper.argtypes = [ctypes.c_uint]
libc.towupper.restype = ctypes.c_uint
libc.towlower.argtypes = [ctypes.c_uint]
libc.towlower.restype = ctypes.c_uint

CODES = [c for c in range(0x80, 0x110000) if not 0xD800 <= c <= 0xDFFF]
CLASSES = ["alpha", "alnum", "upper", "lower", "punct", "space", "blank", "cntrl", "graph", "print", "digit", "xdigit"]
sets = {}
for name in CLASSES:
    t = libc.wctype(name.encode())
    sets[name] = {c for c in CODES if libc.iswctype(c, t)}

assert sets["alnum"] == sets["alpha"]
assert not sets["digit"] and not sets["xdigit"]
assert sets["graph"] == sets["alpha"] | sets["punct"]
assert sets["print"] == sets["graph"] | sets["blank"]


def ranges(s):
    out = []
    for c in sorted(s):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


print("//! Generated by `gen_ctype.py` from glibc iswctype(3), towupper(3) and towlower(3).")
print("//! Do not edit. Code points from U+0080 up only.")
print("#![allow(clippy::unreadable_literal)]")
print()
for name in ["alpha", "upper", "lower", "punct", "space", "blank", "cntrl"]:
    print(f"pub(super) const {name.upper()}: &[(u32, u32)] = &[")
    for lo, hi in ranges(sets[name]):
        print(f"    ({lo:#x}, {hi:#x}),")
    print("];")
    print()
for name, fn in [("TOUPPER", libc.towupper), ("TOLOWER", libc.towlower)]:
    print(f"pub(super) const {name}: &[(u32, u32)] = &[")
    for c in CODES:
        m = fn(c)
        if m != c:
            print(f"    ({c:#x}, {m:#x}),")
    print("];")
    print()
