#!/usr/bin/env bash
# Regenerates src/options/table.in, the tmux 3.8 options table, from the
# reference source tree (options-table.c `options_table[]` and
# `options_other_names[]`). The C compiler expands the hook macros and the
# status-format default, so the output is exactly the table tmux builds.
#
#   crates/vtmux-core/src/options/gen_table.sh > crates/vtmux-core/src/options/table.in
#
# Build-time defaults are the ones the reference is built with (Makefile.am:
# TMUX_MOUSE=1, configure: TMUX_TERM=tmux-256color, TMUX_LOCK_CMD="lock -np").
# libevent is not needed: a stub event.h satisfies tmux.h.
#
# Needs a C compiler and the tmux 3.8 source tree (`cargo xtask ref-tmux`
# leaves it at ~/.cache/vtmux/tmux-3.8-src; override with VTMUX_TMUX_SRC).
set -euo pipefail

SRC="${VTMUX_TMUX_SRC:-${XDG_CACHE_HOME:-$HOME/.cache}/vtmux/tmux-3.8-src}"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

mkdir -p "$TMP/inc"
printf 'struct event { int unused; };\nstruct event_base;\n' > "$TMP/inc/event.h"

cat > "$TMP/gen.c" <<'C'
#include <stdlib.h>
#include "options-table.c"

static void
rust_str(const char *s)
{
	putchar('"');
	for (; *s != '\0'; s++) {
		if (*s == '"' || *s == '\\')
			putchar('\\');
		putchar(*s);
	}
	putchar('"');
}

static const char *
scope_name(int scope)
{
	switch (scope) {
	case OPTIONS_TABLE_SERVER:
		return "Server";
	case OPTIONS_TABLE_SESSION:
		return "Session";
	case OPTIONS_TABLE_WINDOW:
		return "Window";
	case OPTIONS_TABLE_WINDOW|OPTIONS_TABLE_PANE:
		return "WindowPane";
	}
	fprintf(stderr, "unknown scope %d\n", scope);
	exit(1);
}

int
main(void)
{
	const struct options_table_entry	*oe;
	const struct options_name_map		*map;
	const char				**cp;
	unsigned				 n = 0;

	for (oe = options_table; oe->name != NULL; oe++)
		n++;
	printf("// @generated by gen_table.sh from tmux 3.8 options-table.c; do not edit.\n");
	printf("pub(super) static TABLE: [OptionDef; %u] = [\n", n);
	for (oe = options_table; oe->name != NULL; oe++) {
		printf("    OptionDef {\n        name: ");
		rust_str(oe->name);
		printf(",\n        scope: Scope::%s,\n        kind: ",
		    scope_name(oe->scope));
		switch (oe->type) {
		case OPTIONS_TABLE_STRING:
			if (oe->pattern != NULL) {
				if (strcmp(oe->pattern, "[0-9]*x[0-9]*") != 0) {
					fprintf(stderr, "new pattern %s\n",
					    oe->pattern);
					exit(1);
				}
				printf("Kind::String(StringCheck::Size)");
			} else if (oe->flags & OPTIONS_TABLE_IS_STYLE)
				printf("Kind::String(StringCheck::Style)");
			else if (oe->flags & OPTIONS_TABLE_IS_COLOUR)
				printf("Kind::String(StringCheck::Colour)");
			else if (strcmp(oe->name, "default-shell") == 0)
				printf("Kind::String(StringCheck::Shell)");
			else
				printf("Kind::String(StringCheck::None)");
			break;
		case OPTIONS_TABLE_NUMBER:
			printf("Kind::Number { min: %u, max: %u }",
			    oe->minimum, oe->maximum);
			break;
		case OPTIONS_TABLE_KEY:
			printf("Kind::Key");
			break;
		case OPTIONS_TABLE_COLOUR:
			printf("Kind::Colour");
			break;
		case OPTIONS_TABLE_FLAG:
			printf("Kind::Flag");
			break;
		case OPTIONS_TABLE_CHOICE:
			printf("Kind::Choice(&[");
			for (cp = oe->choices; *cp != NULL; cp++) {
				if (cp != oe->choices)
					printf(", ");
				rust_str(*cp);
			}
			printf("])");
			break;
		case OPTIONS_TABLE_COMMAND:
			printf("Kind::Command");
			break;
		}
		printf(",\n        array: %s,\n        hook: %s,\n",
		    (oe->flags & OPTIONS_TABLE_IS_ARRAY) ? "true" : "false",
		    (oe->flags & OPTIONS_TABLE_IS_HOOK) ? "true" : "false");
		printf("        separator: ");
		if (oe->separator == NULL)
			printf("None");
		else {
			printf("Some(");
			rust_str(oe->separator);
			printf(")");
		}
		printf(",\n        default: ");
		if (oe->default_arr != NULL) {
			printf("DefaultValue::List(&[\n");
			for (cp = oe->default_arr; *cp != NULL; cp++) {
				printf("            ");
				rust_str(*cp);
				printf(",\n");
			}
			printf("        ])");
		} else if (oe->type == OPTIONS_TABLE_STRING ||
		    oe->type == OPTIONS_TABLE_COMMAND ||
		    (oe->flags & OPTIONS_TABLE_IS_ARRAY)) {
			printf("DefaultValue::Str(");
			rust_str(oe->default_str == NULL ? "" : oe->default_str);
			printf(")");
		} else switch (oe->type) {
		case OPTIONS_TABLE_NUMBER:
			printf("DefaultValue::Number(%lld)", oe->default_num);
			break;
		case OPTIONS_TABLE_KEY:
			printf("DefaultValue::Key(Key::from_code(%#llx))",
			    (unsigned long long)oe->default_num);
			break;
		case OPTIONS_TABLE_COLOUR:
			/* colour.c: 8 is "default", the only one used. */
			if (oe->default_num != 8) {
				fprintf(stderr, "new colour default\n");
				exit(1);
			}
			printf("DefaultValue::Colour(Colour::Default)");
			break;
		case OPTIONS_TABLE_FLAG:
			printf("DefaultValue::Flag(%s)",
			    oe->default_num ? "true" : "false");
			break;
		case OPTIONS_TABLE_CHOICE:
			printf("DefaultValue::Choice(%lld)", oe->default_num);
			break;
		default:
			exit(1);
		}
		printf(",\n    },\n");
	}
	printf("];\n\n");
	printf("pub(super) static ALIASES: &[(&str, &str)] = &[\n");
	for (map = options_other_names; map->from != NULL; map++) {
		printf("    (");
		rust_str(map->from);
		printf(", ");
		rust_str(map->to);
		printf("),\n");
	}
	printf("];\n");
	return (0);
}
C

${CC:-cc} -o "$TMP/gen" -I "$TMP/inc" -I "$SRC" \
    -DTMUX_TERM='"tmux-256color"' -DTMUX_MOUSE=1 -DTMUX_LOCK_CMD='"lock -np"' \
    "$TMP/gen.c"
"$TMP/gen"
