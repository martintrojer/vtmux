#!/usr/bin/env bash
# Regenerates src/keys/defaults.in, the 3.8 default key bindings, from the
# reference tmux source tree (key-bindings.c `key_bindings_init`, the
# `defaults[]` array and the DEFAULT_*_MENU macros it concatenates). The C
# preprocessor and string-literal rules do the macro expansion, so the output
# is exactly the strings tmux parses at start-up.
#
#   crates/vtmux-core/src/keys/gen_defaults.sh > crates/vtmux-core/src/keys/defaults.in
#
# Needs a C compiler and the tmux 3.8 source tree (`cargo xtask ref-tmux`
# leaves it at ~/.cache/vtmux/tmux-3.8-src; override with VTMUX_TMUX_SRC).
set -euo pipefail

SRC="${VTMUX_TMUX_SRC:-${XDG_CACHE_HOME:-$HOME/.cache}/vtmux/tmux-3.8-src}/key-bindings.c"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

{
    # The menu macros: from the first #define to the line before the first
    # static declaration.
    awk '/^#define DEFAULT_SESSION_MENU/{p=1} /^static int key_bindings_cmp/{p=0} p' "$SRC"
    echo 'static const char *const defaults[] = {'
    awk '/static const char \*const defaults\[\] = \{/{p=1;next} p&&/^\t};/{p=0} p' "$SRC"
    echo '};'
    cat <<'C'
#include <stdio.h>
int main(void) {
    unsigned i;
    printf("// @generated by gen_defaults.sh from tmux 3.8 key-bindings.c; do not edit.\n");
    printf("pub(super) static DEFAULT_BINDINGS: [&str; %u] = [\n", (unsigned)(sizeof defaults / sizeof defaults[0]));
    for (i = 0; i < sizeof defaults / sizeof defaults[0]; i++) {
        const char *s = defaults[i];
        printf("    \"");
        for (; *s != '\0'; s++) {
            if (*s == '"' || *s == '\\') putchar('\\');
            putchar(*s);
        }
        printf("\",\n");
    }
    printf("];\n");
    return 0;
}
C
} > "$TMP/gen.c"
cc -o "$TMP/gen" "$TMP/gen.c"
"$TMP/gen"
