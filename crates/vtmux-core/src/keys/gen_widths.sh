#!/usr/bin/env bash
# Regenerates src/keys/widths.in: the display width tmux 3.8 gives a code point
# (utf8.c `utf8_width`, built without utf8proc as the reference is).
#
#   crates/vtmux-core/src/keys/gen_widths.sh > crates/vtmux-core/src/keys/widths.in
#
# The width of a Unicode key is part of its key code (`UTF8_SET_WIDTH`), so it
# decides `list-keys` order. tmux's rule is: the codepoint-widths cache
# (`utf8_default_width_cache` in utf8.c, parsed below) first, then glibc
# `wcwidth` in the locale tmux picks (en_US.UTF-8, else C.UTF-8), a negative
# result being 0 for C1 controls and 1 for everything else.
#
# Needs a C compiler and the tmux 3.8 source tree (VTMUX_TMUX_SRC).
set -euo pipefail

SRC="${VTMUX_TMUX_SRC:-${XDG_CACHE_HOME:-$HOME/.cache}/vtmux/tmux-3.8-src}/utf8.c"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

{
    echo '#define _GNU_SOURCE'
    echo '#include <locale.h>'
    echo '#include <stdio.h>'
    echo '#include <wchar.h>'
    echo 'static const struct { unsigned wc; int width; } cache[] = {'
    sed -n '/^static struct utf8_width_item utf8_default_width_cache\[\] = {/,/^};/p' "$SRC" |
        sed -n 's/^[[:space:]]*{ \.wc = \(0x[0-9A-Fa-f]*\), \.width = \([0-9]\) },.*/    { \1, \2 },/p'
    echo '};'
    cat <<'C'
static int width(unsigned wc) {
    int w;
    for (unsigned i = 0; i < sizeof cache / sizeof cache[0]; i++)
        if (cache[i].wc == wc) return cache[i].width;
    w = wcwidth((wchar_t)wc);
    if (w < 0) w = (wc >= 0x80 && wc <= 0x9f) ? 0 : 1;
    return w;
}
static void ranges(const char *name, int want) {
    unsigned wc, start = 0;
    int in = 0, first = 1;
    printf("pub(super) static %s: &[(u32, u32)] = &[", name);
    for (wc = 1; wc <= 0x110000; wc++) {
        int hit = wc < 0x110000 && !(wc >= 0xd800 && wc < 0xe000) && width(wc) == want;
        if (hit && !in) { start = wc; in = 1; }
        if (!hit && in) {
            printf("%s(0x%x, 0x%x)", first ? "" : ", ", start, wc - 1);
            first = 0; in = 0;
        }
    }
    printf("];\n");
}
int main(void) {
    if (setlocale(LC_CTYPE, "en_US.UTF-8") == NULL && setlocale(LC_CTYPE, "C.UTF-8") == NULL)
        return 1;
    printf("// @generated by gen_widths.sh from tmux 3.8 utf8.c and glibc wcwidth; do not edit.\n");
    printf("// Code points not listed are width 1. Surrogates are not scalar values and are skipped.\n");
    ranges("ZERO", 0);
    ranges("WIDE", 2);
    return 0;
}
C
} > "$TMP/gen.c"
cc -o "$TMP/gen" "$TMP/gen.c"
"$TMP/gen"
