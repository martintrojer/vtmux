#!/usr/bin/env python3
"""Regenerates wcwidth.rs's tables from the host glibc, the wcwidth(3) that the
reference tmux 3.8 uses (it is not built with utf8proc; utf8.c:575).

    python3 crates/vtmux-core/src/format/gen_wcwidth.py > crates/vtmux-core/src/format/wcwidth_tables.rs

A negative wcwidth is 1, except C1 controls U+0080..U+009F, which are 0 (utf8.c:577-582).
Code points below U+00A0 are handled by the caller; only ranges of width 0 and 2 are listed."""
import ctypes

libc = ctypes.CDLL(None)
libc.setlocale(6, b"C.UTF-8")  # LC_CTYPE
libc.wcwidth.argtypes = [ctypes.c_int]


def width(c):
    r = libc.wcwidth(c)
    return r if r >= 0 else 1


ranges = {0: [], 2: []}
cur = None
for c in range(0xA0, 0x110000):
    if 0xD800 <= c <= 0xDFFF:
        cur = None
        continue
    w = width(c)
    if w == 1:
        cur = None
    elif cur and cur[2] == w and cur[1] == c - 1:
        cur[1] = c
    else:
        cur = [c, c, w]
        ranges[w].append(cur)

print("//! Generated by `gen_wcwidth.py` from glibc wcwidth(3). Do not edit.\n")
for name, w in (("ZERO", 0), ("WIDE", 2)):
    print(f"pub(super) const {name}: &[(u32, u32)] = &[")
    for a, b, _ in ranges[w]:
        print(f"    (0x{a:x}, 0x{b:x}),")
    print("];\n")
