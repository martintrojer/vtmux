# reference tmux 3.8. Usage:
#   crates/vtmux-core/tests/format_cases.sh > crates/vtmux-core/src/format/golden_rows.in
# (the output is a whole `fn rows()`, `include!`d by golden.rs)
#
# Each case is expanded by the PLAIN path, `set -gF @out '<fmt>'` then
# `show -gv @out` (format.c:6925 format_expand), not `display -p`, which uses
# format_expand_time (cmd-display-message.c:144) and turns `%%` into `%`.
# Case strings must not contain `%`, a newline or a single quote.
#
# The fixture the Rust test context mirrors (golden.rs, `ctx()`):
#   new-session -d -s s -n w ; select-pane -T t
#   set -g @x 1 ; @zero 0 ; @empty '' ; @name hello ; @loop 'x#{E:@loop}y'
#   @cond '#{?@x,yes,no}' ; @esc 'a#,b' ; @epoch 86400
# TZ is pinned to UTC so `#{t:...}` rows match the test context's UTC
# `local_time`.
