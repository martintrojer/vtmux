rust_str() { python3 -c '
import sys, unicodedata
out = []
for ch in sys.argv[1]:
    if ch != " " and unicodedata.category(ch)[0] in "MZCS" and ord(ch) > 127: out.append("\\u{%x}" % ord(ch))
    elif ch == "\\": out.append("\\\\")
    elif ch == "\"": out.append("\\\"")
    elif ord(ch) < 32 or ord(ch) == 127: out.append("\\u{%x}" % ord(ch))
    else: out.append(ch)
sys.stdout.write("".join(out))
' "$1"; }
run() {
    t set -gF @out "$1" || { echo "reference server failed on: $1" >&2; exit 1; }
    t show -gv @out || { echo "reference server failed on: $1" >&2; exit 1; }
}
get() {
    local out
    out=$(run "$1"; echo x)
    out=${out%x}
    printf '%s' "${out%$'\n'}"
}

# row 'fmt'            -> r("fmt", "<reference output>")
row() {
    local out
    out=$(get "$1")
    printf '        r("%s", "%s"), // set -gF @out '"'"'%s'"'"' ; show -gv @out\n' \
        "$(rust_str "$1")" "$(rust_str "$out")" "$1"
}

# rowdef 'fmt' 'vtmux'  -> a modifier not implemented yet: vtmux expands it to nothing, so
# the expectation is given by hand; the reference value is kept in the comment.
rowdef() {
    local out
    out=$(get "$1")
    printf '        r("%s", "%s"), // deferred; set -gF @out '"'"'%s'"'"' ; show -gv @out gives "%s"\n' \
        "$(rust_str "$1")" "${2-}" "$1" "$(rust_str "$out")"
}

# rowgen 'rust fmt expr' 'rust expected expr' 'shell fmt' 'shell expected'
# Long cases: the Rust side builds the string; this side proves the expectation.
rowgen() {
    local out
    out=$(get "$3")
    if [ "$out" != "$4" ]; then
        echo "reference gave '${out:0:60}...' for $1, expected $2" >&2
        exit 1
    fi
    printf '        r(%s, %s), // %s via set -gF @out ; show -gv @out\n' "$1" "$2" "$1"
}

