#   server env: PATH=/usr/bin:/bin HOME=/ SHELL=/bin/sh LANG=C.UTF-8 TZ=UTC CL1=x CL2=y
#   start-server ; set -g exit-empty off ; set -g update-environment ''
#   new-session -d -s s -n w "printf 'alpha\nbeta Foo\n'; exec sleep 3600" ; select-pane -T t
#   set-environment FOO bar ; -r GONE ; -h HID sec ; ZED ''
# TZ=UTC is set in the server's environment so `#{t:...}` rows match the test context's
# UTC `local_time`; `@epoch` is 86400.
# `rows_nosession()` come from a second server that has no session.
