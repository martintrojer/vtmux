rust_str() { sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }
run() { t set -gF @out "$1"; t show -gv @out; }

# row 'fmt'            -> r("fmt", "<reference output>")
row() {
    local out
    out=$(run "$1"; echo x); out=${out%x}; out=${out%$'\n'}
    printf '        r("%s", "%s"), // set -gF @out '"'"'%s'"'"' ; show -gv @out\n' \
        "$(printf '%s' "$1" | rust_str)" "$(printf '%s' "$out" | rust_str)" "$1"
}

# rowdef 'fmt' 'vtmux'  -> a modifier M0 defers: vtmux expands it to nothing, so
# the expectation is given by hand; the reference value is kept in the comment.
rowdef() {
    local out
    out=$(run "$1"; echo x); out=${out%x}; out=${out%$'\n'}
    printf '        r("%s", "%s"), // deferred in M0; set -gF @out '"'"'%s'"'"' ; show -gv @out gives "%s"\n' \
        "$(printf '%s' "$1" | rust_str)" "${2-}" "$1" "$out"
}

# rowgen 'rust fmt expr' 'rust expected expr' 'shell fmt' 'shell expected'
# Long cases: the Rust side builds the string; this side proves the expectation.
rowgen() {
    local out
    out=$(run "$3"; echo x); out=${out%x}; out=${out%$'\n'}
    if [ "$out" != "$4" ]; then
        echo "reference gave '${out:0:60}...' for $1, expected $2" >&2
        exit 1
    fi
    printf '        r(%s, %s), // %s via set -gF @out ; show -gv @out\n' "$1" "$2" "$1"
}

nest() { # nest N: N nested true conditionals around "ok"
