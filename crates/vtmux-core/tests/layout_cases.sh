# Regenerates crates/vtmux-core/src/layout/golden_cases.in from the reference
# tmux 3.8. Usage:
#   crates/vtmux-core/tests/layout_cases.sh > crates/vtmux-core/src/layout/golden_cases.in
#
# Each case is a fresh isolated server (env -u TMUX -u TMUX_PANE, -L, -f
# /dev/null, SHELL=/bin/sh, EDITOR/VISUAL unset), `new -d -x W -y H`, then the
# ops run in order as tmux commands (the Rust test replays the same text on the
# model). After the ops:
#   v2 = display -p '#{window_layout}'                       (normal client)
#   v1 = the same through `-C attach`, WITHOUT new-layouts   (layout-custom.c)
# `errs` is the stderr of every op that failed, one line each.
# Special ops: `@save` / `@restore` keep and re-apply the current v2 string
# (`select-layout <string>`); `@save1` / `@restore1` do the same with v1.
set -euo pipefail
set -f

REF="${VTMUX_REFERENCE_TMUX:-${XDG_CACHE_HOME:-$HOME/.cache}/vtmux/tmux-3.8/bin/tmux}"
SOCK="vtmux-layout-cases-$$"
unset EDITOR VISUAL
export SHELL=/bin/sh
t() { env -u TMUX -u TMUX_PANE "$REF" -L "$SOCK" -f /dev/null "$@"; }
trap 't kill-server 2>/dev/null || true' EXIT

rust_str() { sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

# v1 string for a body: python's independent rotate-and-add checksum.
v1str() {
    python3 - "$1" <<'PY'
import sys
b = sys.argv[1]
c = 0
for ch in b.encode():
    c = ((c >> 1) + ((c & 1) << 15)) & 0xFFFF
    c = (c + (ch - 256 if ch > 127 else ch)) & 0xFFFF
print("%04x,%s" % (c, b))
PY
}

v1_now() {
    printf "display -p '#{window_layout}'\n" | t -C attach -t s | grep -v '^%' | head -1
}

# Replays OPS on a fresh server (see the header); sets ERRS.
replay_ops() {
    local w=$1 h=$2
    shift 2
    t kill-server 2>/dev/null || true
    t new-session -d -s s -x "$w" -y "$h"
    ERRS="" SAVED="" SAVED1=""
    local op out
    for op in "$@"; do
        case "$op" in
        @save) SAVED=$(t display -p '#{window_layout}') ;;
        @save1) SAVED1=$(v1_now) ;;
        @restore | @restore1)
            if [ "$op" = @restore ]; then out=$(t select-layout "$SAVED" 2>&1) || true
            else out=$(t select-layout "$SAVED1" 2>&1) || true; fi
            [ -z "$out" ] || ERRS+="$out"$'\n'
            ;;
        *)
            # shellcheck disable=SC2086
            out=$(t $op 2>&1) || true
            [ -z "$out" ] || ERRS+="$out"$'\n'
            ;;
        esac
    done
    ERRS=${ERRS%$'\n'}
}

esc() { printf '%s' "$1" | rust_str | sed ':a;N;$!ba;s/\n/\\n/g'; }

# case NAME W H OP...
# Besides the final v2/v1 strings, records what the reference itself makes of
# them: `re2`/`re1` are `display -p '#{window_layout}'` after `select-layout
# <v2>` / `select-layout <v1>` on the same final state, `re2_err`/`re1_err`
# the stderr of that select-layout. Parsing is not the identity in tmux
# (fix_offsets, last-pane renumbering, collapsed nodes), so the parse-back
# tests compare against these, not against the emitted string.
case_() {
    local name=$1 w=$2 h=$3
    shift 3
    replay_ops "$w" "$h" "$@"
    local errs=$ERRS v2 v1 re2 re2_err re1 re1_err
    v2=$(t display -p '#{window_layout}')
    v1=$(v1_now)
    replay_ops "$w" "$h" "$@"
    re2_err=$(t select-layout "$v2" 2>&1) || true
    re2=$(t display -p '#{window_layout}')
    replay_ops "$w" "$h" "$@"
    re1_err=$(t select-layout "$v1" 2>&1) || true
    re1=$(t display -p '#{window_layout}')
    local ops="" op
    for op in "$@"; do ops+="\"$(printf '%s' "$op" | rust_str)\", "; done
    printf '        Case { name: "%s", sx: %s, sy: %s, ops: &[%s], errs: "%s", v2: "%s", v1: "%s",\n' \
        "$name" "$w" "$h" "$ops" "$(esc "$errs")" "$(esc "$v2")" "$(esc "$v1")"
    printf '               re2: "%s", re2_err: "%s", re1: "%s", re1_err: "%s" },\n' \
        "$(esc "$re2")" "$(esc "$re2_err")" "$(esc "$re1")" "$(esc "$re1_err")"
}

