#!/usr/bin/env bash
# Regenerates crates/vtmux-core/src/term_features/terminfo.rs: for each terminal
# vtmux knows (D8, D-007), the names of tmux's `tty_term_codes` (tty-term.c) its
# terminfo entry has, as `tty_term_read_list` reads them (`tigetstr`, `tigetnum`,
# `tigetflag`: a standard boolean is there even when false, so `am` and `bce`
# always are), less the capabilities `Cap` models itself. `#{I/c:name}` answers
# from these (format.c:6309, tty-term.c `tty_term_has_name`).
#
# Needs infocmp (ncurses) with the host's terminfo, Ghostty's terminfo
# ($GHOSTTY_TERMINFO) for xterm-ghostty, and the reference source
# ($VTMUX_REFERENCE_SRC, default ~/.cache/vtmux/tmux-3.8-src).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$HERE/../src/term_features/terminfo.rs"
SRC="${VTMUX_REFERENCE_SRC:-${XDG_CACHE_HOME:-$HOME/.cache}/vtmux/tmux-3.8-src}"
export TERMINFO_DIRS="${GHOSTTY_TERMINFO:-$HOME/.local/opt/ghostty-1.4.0/share/terminfo}:/usr/share/terminfo"
NAMES=$(mktemp)
trap 'rm -f "$NAMES"' EXIT
awk '/tty_term_codes\[\] = /,/^};/' "$SRC/tty-term.c" | grep -o '"[^"]*"' | tr -d '"' >"$NAMES"
MODELLED='^(Tc|RGB|setrgbf|setrgbb|Sync|Smulx|Setulc|Ss|Se|Ms|tsl|fsl|Eneks|Dseks|kmous)$'

names() {
	(infocmp -x -1 "$1" | sed -n '2,$p' | sed 's/^[[:space:]]*//;s/[=#@,].*//'; echo am; echo bce) |
		sort -u | grep -xFf "$NAMES" | grep -vE "$MODELLED" |
		awk '{ printf "%s\"%s\",", (NR % 10 == 1 ? "\n    " : " "), $0 }'
}

table() {
	printf '/// `%s`.\npub(super) const %s: &[&str] = &[%s\n];\n\n' "$1" "$2" "$(names "$1")"
}

{
	cat <<'EOF'
//! Generated by `tests/terminfo_names.sh`; do not edit. Each table is the
//! `tty_term_codes` names (tty-term.c) a terminal's terminfo entry has, less
//! the ones [`super::Cap`] models.

/// Every name in `tty_term_codes`: an override or feature naming anything
/// else changes nothing (`tty_term_apply`).
pub(super) const ALL: &[&str] = &[
EOF
	awk '{ printf "%s\"%s\",", (NR % 10 == 1 ? (NR == 1 ? "    " : "\n    ") : " "), $0 }' "$NAMES"
	printf '\n];\n\n'
	table xterm XTERM
	table xterm-color XTERM_COLOR
	table xterm-mono XTERM_MONO
	table xterm-ghostty XTERM_GHOSTTY
	table tmux-256color TMUX_256COLOR
	table screen SCREEN
} >"$OUT"
# The terminals that share a table must still agree with it.
for pair in xterm-256color:xterm xterm-16color:xterm xterm-88color:xterm xterm-direct:xterm \
	screen-256color:screen; do
	[ "$(names "${pair%%:*}")" = "$(names "${pair#*:}")" ] || {
		echo "${pair%%:*} differs from ${pair#*:}" >&2
		exit 1
	}
done
rustfmt --edition 2024 "$OUT"
